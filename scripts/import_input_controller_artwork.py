#!/usr/bin/env python3
"""Reproduce the pinned Controllercons 2.1 SVG -> Android vector import.

Uses only the Python standard library. --check verifies generated resources,
the Kotlin viewport catalogue and the packaged OFL notice without writing.
--verify-bounds additionally checks pinned visual bounds with Inkscape; it is
not needed to rebuild the resources. SVGs are development sources only.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import math
from pathlib import Path
import re
import subprocess
import sys
import xml.etree.ElementTree as ET


REPO = Path(__file__).resolve().parents[1]
ASSETS = REPO / "third_party_assets/input_controller_artwork"
ANDROID = "http://schemas.android.com/apk/res/android"
SVG = "http://www.w3.org/2000/svg"
ET.register_namespace("android", ANDROID)


def number(value: float) -> str:
    return "0" if abs(value) < 1e-10 else format(value, ".12g")


def attributes(**values: str) -> dict[str, str]:
    return {f"{{{ANDROID}}}{key}": value for key, value in values.items()}


def checked_source(asset: dict) -> bytes:
    source = (ASSETS / asset["source_file"]).read_bytes()
    if hashlib.sha256(source).hexdigest() != asset["source_sha256"]:
        raise ValueError(f"Unpinned source change: {asset['source_file']}")
    git_blob = b"blob " + str(len(source)).encode() + b"\0" + source
    if hashlib.sha1(git_blob).hexdigest() != asset["upstream_blob"]:
        raise ValueError(f"Source differs from upstream Git blob: {asset['source_file']}")
    return source


def convert(source: bytes, asset: dict, manifest: dict) -> bytes:
    svg = ET.fromstring(source)
    if svg.tag != f"{{{SVG}}}svg" or svg.get("viewBox") != "0 0 64 64":
        raise ValueError("Expected the pinned 64 x 64 Controllercons SVG viewport")
    if set(svg.attrib) != {"viewBox", "class"}:
        raise ValueError("Unexpected SVG document attributes")
    if len(svg) != 2:
        raise ValueError("Expected exactly two duotone paths")
    left, top, width, height = asset["viewport_bounds"]
    if not all(math.isfinite(value) for value in (left, top, width, height)) or min(width, height) <= 0:
        raise ValueError("Invalid viewport bounds")
    vector = ET.Element("vector", attributes(
        width=number(width) + "dp", height=number(height) + "dp",
        viewportWidth=number(width), viewportHeight=number(height),
    ))
    group = ET.SubElement(vector, "group", attributes(
        translateX=number(-left), translateY=number(-top),
    ))
    for index, path in enumerate(svg):
        expected = {"class", "d"} if index == 0 else {"class", "d", "opacity"}
        name = "primary" if index == 0 else "secondary"
        if path.tag != f"{{{SVG}}}path" or set(path.attrib) != expected:
            raise ValueError("Unsupported SVG geometry or paint attributes")
        if path.get("class") != "ccsvg__" + name:
            raise ValueError("Unexpected path class or duotone layer order")
        if index == 1 and path.get("opacity") != ".5":
            raise ValueError("Unexpected secondary opacity")
        data = path.attrib["d"]
        if not data.strip() or re.search(r"[^MmLlHhVvCcSsQqTtAaZz0-9eE+.,\s-]", data):
            raise ValueError("Unsupported SVG path syntax")
        ET.SubElement(group, "path", attributes(
            name=name, fillColor="#FFFFFFFF", fillAlpha="1" if index == 0 else "0.5",
            fillType="nonZero", pathData=data,
        ))
    ET.indent(vector, space="    ")
    header = (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<!-- Controllercons 2.1, Copyright (c) 2023 Kieran McClung, OFL-1.1.\n'
        f"     Source: {asset['upstream_path']}\n"
        f"     Revision: {manifest['upstream_commit']}\n"
        '     Original paths; proportional trimmed viewport; white theme tint, original duotone alpha.\n'
        '     License and provenance: third_party_assets/input_controller_artwork/README.md\n'
        '     Regenerate with scripts/import_input_controller_artwork.py. -->\n'
    )
    return (header + ET.tostring(vector, encoding="unicode") + "\n").encode()


def kotlin_catalogue(manifest: dict) -> bytes:
    lines = [
        "package com.ambient.tv.ui.settings", "",
        "import androidx.annotation.DrawableRes",
        "import androidx.compose.runtime.Immutable",
        "import com.ambient.tv.R", "",
        "// Generated by scripts/import_input_controller_artwork.py. Do not edit by hand.",
        "// Controllercons 2.1 / OFL-1.1. See third_party_assets/input_controller_artwork/README.md.",
        "/** The vector viewport expressed in the original 64 x 64 source coordinates. */",
        "@Immutable",
        "internal data class ControllerVectorAsset(",
        "    @param:DrawableRes val drawableRes: Int,",
        "    val left: Float,",
        "    val top: Float,",
        "    val width: Float,",
        "    val height: Float,",
        ") {",
        "    val aspectRatio: Float get() = width / height",
        "}", "",
        "internal object ControllerVectorAssets {",
        "    /** Convert a source point with (x - left) / width and (y - top) / height. */",
        "    val byId: Map<String, ControllerVectorAsset> = mapOf(",
    ]
    for asset in manifest["assets"]:
        resource = Path(asset["output"]).stem
        values = ", ".join(number(value) + "f" for value in asset["viewport_bounds"])
        lines.append(f'        "{asset["id"]}" to ControllerVectorAsset(R.drawable.{resource}, {values}),')
    lines += ["    )", "", "    operator fun get(id: String): ControllerVectorAsset? = byId[id]", "}", ""]
    return "\n".join(lines).encode()


def notice(manifest: dict) -> bytes:
    upstream = manifest["upstream_repository"]
    pin = manifest["upstream_commit"]
    lines = [
        "Controller artwork: Controllercons 2.1 / Duotone", "",
        "Attribution", manifest["credits"], "",
        "Source", upstream, f"Revision: {pin}",
        f"{upstream}/tree/{pin}/versions/2.1/svg/duotone", "",
        "License", "SIL Open Font License 1.1 (OFL-1.1)",
        f"{upstream}/blob/{pin}/LICENSE.txt",
        "The complete original copyright and license follow this notice in the app and are bundled as input_controller_artwork_ofl_1_1.txt.", "",
        "Changes made for Ambient TV", manifest["modifications"], "",
        "The depicted controller designs are unofficial illustrations. Controllercons and Ambient TV do not imply endorsement by the hardware manufacturers. The remote, keyboard and generic fallback artwork in Ambient TV is separate original work.", "",
        "Imported original SVG paths (30 devices)",
        *[asset["upstream_path"] for asset in manifest["assets"]], "",
    ]
    return "\n".join(lines).encode()


def verify_bounds(asset: dict) -> None:
    result = subprocess.run(
        ["inkscape", str(ASSETS / asset["source_file"]), "--query-all"],
        capture_output=True, text=True, check=True,
    )
    actual = [float(value) for value in result.stdout.splitlines()[0].split(",")[1:]]
    if len(actual) != 4 or not all(math.isclose(a, b, abs_tol=.002) for a, b in zip(actual, asset["artwork_bounds"])):
        raise ValueError(f"Visual source bounds changed: {asset['id']}")
    x, y, w, h = actual
    left, top, width, height = asset["viewport_bounds"]
    if not (left <= x and top <= y and left + width >= x + w and top + height >= y + h):
        raise ValueError(f"Trimmed viewport clips artwork: {asset['id']}")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify generated files without writing")
    parser.add_argument("--verify-bounds", action="store_true", help="verify source visual bounds using Inkscape")
    args = parser.parse_args()
    manifest = json.loads((ASSETS / "manifest.json").read_text())
    license_bytes = (ASSETS / manifest["license_file"]).read_bytes()
    if hashlib.sha256(license_bytes).hexdigest() != manifest["license_sha256"]:
        raise ValueError("The pinned upstream license has changed")
    assets = manifest["assets"]
    if len(assets) != 30 or len({asset["id"] for asset in assets}) != 30:
        raise ValueError("Expected all 30 distinct Controllercons 2.1 devices")
    generated = []
    for asset in assets:
        source = checked_source(asset)
        if args.verify_bounds:
            verify_bounds(asset)
        generated.append((REPO / asset["output"], convert(source, asset, manifest)))
    generated += [
        (REPO / "app/src/main/java/com/ambient/tv/ui/settings/ControllerVectorAssets.kt", kotlin_catalogue(manifest)),
        (REPO / "app/src/main/res/raw/input_controller_artwork_notice.txt", notice(manifest)),
        (REPO / "app/src/main/res/raw/input_controller_artwork_ofl_1_1.txt", license_bytes),
    ]
    different = [str(path.relative_to(REPO)) for path, content in generated
                 if not path.exists() or path.read_bytes() != content]
    if args.check and different:
        print("Generated files need updating:\n" + "\n".join(different), file=sys.stderr)
        return 1
    if not args.check:
        for path, content in generated:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content)
    print(f"{'Verified' if args.check else 'Generated'} {len(assets)} native controller vectors, "
          "viewport catalogue and complete attribution/license.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
