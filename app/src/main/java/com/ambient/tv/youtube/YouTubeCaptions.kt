import com.ambient.tv.domain.model.MediaTrackType
import java.io.File
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.coroutineScope
import kotlinx.coroutines.launch
import kotlinx.coroutines.runInterruptible
import kotlinx.coroutines.sync.Mutex
import kotlinx.coroutines.sync.Semaphore
import kotlinx.coroutines.sync.withLock
import kotlinx.coroutines.sync.withPermit
import kotlinx.coroutines.withContext
import java.util.concurrent.TimeUnit
import okhttp3.OkHttpClient
import okhttp3.Request

/** One caption track of a YouTube video (WebVTT URL from SmartTube's player response). */
data class YouTubeCaption(
    val url: String,
    val languageCode: String?,
    val name: String?,
    val autoGenerated: Boolean,
)

/** SmartTube marks automatic tracks with a trailing "*" in the name; the panel shows the plain name. */
internal fun youtubeCaptionTitle(caption: YouTubeCaption): String? =
    caption.name?.trim()?.removeSuffix("*")?.trim()?.takeIf(String::isNotBlank) ?: caption.languageCode

/**
 * MPV/VLC subtitle list for [captions]; [files] maps a caption URL to its local, normalized copy.
 * Tracks without a local copy are left out, so the panel only offers what the player can open.
 * At most [limit] tracks, manual captions first (automatic ones are the fallback of a language).
 */
internal fun youtubeCaptionTracks(captions: List<YouTubeCaption>, files: Map<String, String>, limit: Int = 16): List<MediaTrack> =
    youtubeCaptionsInLoadOrder(captions, limit).mapNotNull { caption ->
        val file = files[caption.url] ?: return@mapNotNull null
        MediaTrack(
            id = null,
            type = MediaTrackType.SUBTITLE,
            codec = "vtt",
            language = caption.languageCode,
            languageCode = caption.languageCode,
            title = youtubeCaptionTitle(caption),
            channels = null,
            selected = false,
            forced = false,
            externalUrl = file,
        )
    }

internal fun youtubeCaptionsInLoadOrder(captions: List<YouTubeCaption>, limit: Int = 16): List<YouTubeCaption> =
    captions.filter { it.url.isNotBlank() }.distinctBy { it.url }.sortedBy { it.autoGenerated }.take(limit)

private val vttLeftAlign = setOf("start", "left")

/**
 * Removes the left-edge placement of YouTube's automatic captions (`align:start position:0%`) from
 * every cue timing line, so MPV and VLC center them like manual captions. Other placements stay.
 */
internal fun normalizeYouTubeVtt(text: String): String = text.lineSequence().joinToString("\n") { line ->
    val arrow = line.indexOf("-->")
    if (arrow < 0) return@joinToString line
    val afterArrow = line.substring(arrow + 3).trimStart()
    val endTime = afterArrow.substringBefore(' ').substringBefore('\t')
    val settings = afterArrow.substring(endTime.length).trim().split(Regex("[ \t]+")).filter(String::isNotBlank)
    if (settings.isEmpty()) return@joinToString line
    val values = settings.associate { it.substringBefore(':') to it.substringAfter(':', "") }
    val align = values["align"]?.lowercase() ?: return@joinToString line
    if (align !in vttLeftAlign) return@joinToString line
    val position = values["position"]?.substringBefore(',')?.removeSuffix("%")?.trim()
    val positionValue = if (position == null) 0f else position.toFloatOrNull() ?: return@joinToString line
    if (positionValue > YouTubeCueNormalizer.LEFT_EDGE_POSITION * 100f) return@joinToString line
    val kept = settings.filterNot { it.substringBefore(':') in setOf("align", "position", "size") }
    line.substring(0, arrow) + "--> " + endTime + kept.joinToString("") { " $it" }
}

/** Parallel caption downloads per video; enough to be quick without flooding YouTube. */
internal const val YOUTUBE_CAPTION_DOWNLOADS = 3

/** Caption copies older than this are removed from the app cache. */
internal const val YOUTUBE_CAPTION_MAX_AGE_MS = 7L * 24 * 60 * 60 * 1000

/**
 * The finished part of [results] in load order: every slot up to the first one still loading
 * (null). Failed slots ("") are skipped. Manual captions come first in the load order, so the
 * subtitle choice never sees an automatic track before the manual track of the same language.
 */
internal fun youtubeCaptionsReadyInOrder(urls: List<String>, results: List<String?>): Map<String, String> = buildMap {
    for (index in urls.indices) {
        val result = results.getOrNull(index) ?: break
        if (result.isNotEmpty()) put(urls[index], result)
    }
}

/** Files in the caption cache whose last change is older than [maxAgeMs] at [nowMs]. */
internal fun youtubeCaptionFilesToDelete(files: List<File>, nowMs: Long, maxAgeMs: Long = YOUTUBE_CAPTION_MAX_AGE_MS): List<File> =
    files.filter { it.isFile && nowMs - it.lastModified() > maxAgeMs }

/** Local, normalized WebVTT copies of YouTube captions for MPV and VLC. */
object YouTubeCaptionFiles {
    private val client by lazy {
        OkHttpClient.Builder().connectTimeout(10, TimeUnit.SECONDS).readTimeout(15, TimeUnit.SECONDS).build()
    }
    @Volatile private var cleaned = false

    /**
     * Downloads each caption once per video (cached under the app cache), at most
     * [YOUTUBE_CAPTION_DOWNLOADS] at a time, and reports caption URL to file:// URL through
     * [onReady] as soon as the next tracks in load order are done. Failures are skipped. The
     * first call per app start removes copies older than 7 days.
     */
    suspend fun prepare(
        context: Context,
        videoId: String,
        captions: List<YouTubeCaption>,
        headers: Map<String, String>,
        onReady: (Map<String, String>) -> Unit,
    ) = withContext(Dispatchers.IO) {
        val dir = context.cacheDir.resolve("youtube_captions").apply { mkdirs() }
        if (!cleaned) {
            cleaned = true
            youtubeCaptionFilesToDelete(dir.listFiles()?.toList().orEmpty(), System.currentTimeMillis()).forEach { it.delete() }
        }
        val safeId = videoId.replace(Regex("[^A-Za-z0-9_-]"), "_")
        val ordered = youtubeCaptionsInLoadOrder(captions)
        val urls = ordered.map { it.url }
        val results = MutableList<String?>(ordered.size) { null }
        val lock = Mutex()
        var published = emptyMap<String, String>()
        val limit = Semaphore(YOUTUBE_CAPTION_DOWNLOADS)
        coroutineScope {
            ordered.forEachIndexed { index, caption ->
                launch {
                    val result = limit.withPermit {
                        val safeLanguage = (caption.languageCode ?: "und").replace(Regex("[^A-Za-z0-9_-]"), "_")
                        val file = dir.resolve("${safeId}_${index}_${safeLanguage}${if (caption.autoGenerated) "_auto" else ""}.vtt")
                        val ready = file.length() > 0 || runInterruptible { runCatching { download(caption.url, headers, file) } }
                            .onFailure { com.ambient.tv.diagnostics.DiagnosticLog.warn("youtube-captions", "caption ${caption.languageCode} not loaded: ${it.javaClass.simpleName}") }
                            .getOrDefault(false)
                        if (ready) android.net.Uri.fromFile(file).toString() else ""
                    }
                    lock.withLock {
                        results[index] = result
                        val ready = youtubeCaptionsReadyInOrder(urls, results)
                        if (ready.size != published.size) {
                            published = ready
                            withContext(Dispatchers.Main) { onReady(ready) }
                        }
                    }
                }
            }
        }
    }

    private fun download(url: String, headers: Map<String, String>, target: File): Boolean {
        val request = Request.Builder().url(url).apply {
            headers.forEach { (name, value) -> header(name, value) }
        }.build()
        client.newCall(request).execute().use { response ->
            if (!response.isSuccessful) return false
            val body = response.body.string()
            if (!body.trimStart('\uFEFF').startsWith("WEBVTT")) return false
            val temp = File(target.parentFile, target.name + ".part")
            temp.writeText(normalizeYouTubeVtt(body))
            return temp.renameTo(target)
        }
    }
}
