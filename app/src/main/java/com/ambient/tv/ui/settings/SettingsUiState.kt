private val ACCENT_HEX = Regex("^#[0-9A-Fa-f]{6}$")

/**
 * This state with every field that must not be stored half-typed taken from [saved]:
 * server addresses, ports, HTTPS/base path, user names, passwords, tokens, MAC addresses,
 * the TVHeadend stream profile, the Spotify client ID and device name, and an incomplete
 * custom accent colour. These are stored when the page or Settings is left, or by a
 * connect/test/sign-in action.
 */
internal fun SettingsUiState.deferredSettingsFrom(saved: SettingsUiState): SettingsUiState = copy(
    host = saved.host, port = saved.port, plexUseHttps = saved.plexUseHttps, token = saved.token,
    macAddress = saved.macAddress, selectedMachineIdentifier = saved.selectedMachineIdentifier,
    jellyfinHost = saved.jellyfinHost, jellyfinPort = saved.jellyfinPort, jellyfinUseHttps = saved.jellyfinUseHttps,
    jellyfinBasePath = saved.jellyfinBasePath, jellyfinUsername = saved.jellyfinUsername,
    jellyfinPassword = saved.jellyfinPassword, jellyfinMacAddress = saved.jellyfinMacAddress,
    embyHost = saved.embyHost, embyPort = saved.embyPort, embyUseHttps = saved.embyUseHttps,
    embyBasePath = saved.embyBasePath, embyUsername = saved.embyUsername,
    embyPassword = saved.embyPassword, embyMacAddress = saved.embyMacAddress,
    tvheadendHost = saved.tvheadendHost, tvheadendPort = saved.tvheadendPort, tvheadendUseHttps = saved.tvheadendUseHttps,
    tvheadendUsername = saved.tvheadendUsername, tvheadendPassword = saved.tvheadendPassword,
    tvheadendMacAddress = saved.tvheadendMacAddress, tvheadendStreamProfile = saved.tvheadendStreamProfile,
    pendingSourceWakeMacs = saved.pendingSourceWakeMacs, pendingSourceWakeAuto = saved.pendingSourceWakeAuto,
    spotifyClientId = saved.spotifyClientId, spotifyDeviceName = saved.spotifyDeviceName,
    customAccentHex = customAccentHex.takeIf { ACCENT_HEX.matches(it) } ?: saved.customAccentHex,
    customPlaybackAccentHex = customPlaybackAccentHex.takeIf { ACCENT_HEX.matches(it) } ?: saved.customPlaybackAccentHex,
)


