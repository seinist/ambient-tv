package com.ambient.tv.ui.common

import androidx.compose.runtime.remember
import androidx.compose.runtime.rememberCoroutineScope
import androidx.compose.runtime.withFrameNanos
import androidx.compose.ui.Modifier
import androidx.compose.ui.composed
import androidx.compose.ui.focus.FocusDirection
import androidx.compose.ui.input.key.Key
import androidx.compose.ui.input.key.KeyEventType
import androidx.compose.ui.input.key.key
import androidx.compose.ui.input.key.onPreviewKeyEvent
import androidx.compose.ui.input.key.type
import androidx.compose.ui.platform.LocalFocusManager
import kotlinx.coroutines.delay
import kotlinx.coroutines.Job
import kotlinx.coroutines.launch
import kotlin.math.log2

private const val AccelerationStartRepeat = 15
private const val MaximumMovesPerRepeat = 4

/**
 * Number of focus moves generated by one repeated D-pad event.
 *
 * The first repeats remain one-to-one. Once a key has been held for a while, the number of moves
 * grows logarithmically (2, then 3, then 4) rather than jumping straight into an uncontrollable
 * page-sized skip.
 */
internal fun dpadNavigationRepeatSteps(repeatCount: Int): Int {
    if (repeatCount < AccelerationStartRepeat) return 1
    return (1 + log2((repeatCount.toDouble() + 1.0) / 8.0).toInt())
        .coerceIn(1, MaximumMovesPerRepeat)
}

private fun Key.focusDirectionOrNull(): FocusDirection? = when (this) {
    Key.DirectionLeft -> FocusDirection.Left
    Key.DirectionRight -> FocusDirection.Right
    Key.DirectionUp -> FocusDirection.Up
    Key.DirectionDown -> FocusDirection.Down
    else -> null
}

// Input bookkeeping never contributes to the UI. Keep key and job updates outside the
// snapshot system while the lazy layout handles focus and scroll work.
private class DpadNavigationState {
    var heldKey: Key? = null
    var moveJob: Job? = null
    var lastEventTime = 0L
    var repeatIntervalMillis = 80L
}

/**
 * Accelerates held D-pad directions while preserving normal Compose focus navigation.
 *
 * Extra moves are separated by frames so lazy rows, columns and grids can compose the next target
 * before focus advances again. Repeats arriving while a batch is active are consumed instead of
 * building a backlog that would keep moving after the user releases the key.
 */
fun Modifier.acceleratedDpadNavigation(enabled: Boolean = true): Modifier = composed {
    if (!enabled) return@composed this

    val focusManager = LocalFocusManager.current
    val scope = rememberCoroutineScope()
    val navigation = remember { DpadNavigationState() }

    onPreviewKeyEvent { event ->
        val direction = event.key.focusDirectionOrNull() ?: return@onPreviewKeyEvent false

        if (event.type == KeyEventType.KeyUp) {
            if (navigation.heldKey == event.key) {
                navigation.moveJob?.cancel()
                navigation.moveJob = null
                navigation.heldKey = null
                navigation.lastEventTime = 0L
            }
            return@onPreviewKeyEvent false
        }
        if (event.type != KeyEventType.KeyDown) return@onPreviewKeyEvent false

        if (navigation.heldKey != event.key) {
            navigation.moveJob?.cancel()
            navigation.moveJob = null
            navigation.heldKey = event.key
            navigation.lastEventTime = 0L
            navigation.repeatIntervalMillis = 80L
        }
        val eventTime = event.nativeKeyEvent.eventTime
        if (event.nativeKeyEvent.repeatCount > 1 && navigation.lastEventTime > 0L) {
            navigation.repeatIntervalMillis = (eventTime - navigation.lastEventTime).coerceIn(32L, 160L)
        }
        navigation.lastEventTime = eventTime

        val repeatCount = event.nativeKeyEvent.repeatCount
        val moves = dpadNavigationRepeatSteps(repeatCount)
        if (moves == 1) return@onPreviewKeyEvent false

        // The running batch already represents this held direction. Dropping overlapping repeat
        // events bounds latency and guarantees that releasing the key stops immediately.
        if (navigation.moveJob?.isActive == true) return@onPreviewKeyEvent true
        val stepInterval = (navigation.repeatIntervalMillis / moves).coerceAtLeast(16L)
        navigation.moveJob = scope.launch {
            val started = android.os.SystemClock.uptimeMillis()
            repeat(moves) { step ->
                if (!focusManager.moveFocus(direction)) return@launch
                if (step < moves - 1) {
                    // Prepare the next lazy target, then distribute extra moves over the repeat
                    // interval instead of producing a one-frame burst followed by a long pause.
                    withFrameNanos { }
                    val nextStepAt = started + (step + 1) * stepInterval
                    delay((nextStepAt - android.os.SystemClock.uptimeMillis()).coerceAtLeast(0L))
                }
            }
        }
        true
    }
}
