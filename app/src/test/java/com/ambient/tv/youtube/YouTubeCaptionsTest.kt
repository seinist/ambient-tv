package com.ambient.tv.youtube

import com.ambient.tv.data.local.SubtitleMode
import com.ambient.tv.data.local.SubtitlePreferences
import com.ambient.tv.data.local.SubtitleSelectionPolicy
import com.ambient.tv.domain.model.MediaTrackType
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test

class YouTubeCaptionsTest {
    @Test
    fun leftEdgeSettingsAreRemoved() {
        val vtt = "WEBVTT\nKind: captions\n\n00:00:00.160 --> 00:00:02.869 align:start position:0%\nhi<00:00:00.500><c> there</c>\n"
        assertEquals("WEBVTT\nKind: captions\n\n00:00:00.160 --> 00:00:02.869\nhi<00:00:00.500><c> there</c>\n", normalizeYouTubeVtt(vtt))
    }

    @Test
    fun otherSettingsStay() {
        assertEquals("00:01.000 --> 00:02.000 line:10%", normalizeYouTubeVtt("00:01.000 --> 00:02.000 align:left position:3% size:100% line:10%"))
        listOf(
            "00:01.000 --> 00:02.000",
            "00:01.000 --> 00:02.000 align:end",
            "00:01.000 --> 00:02.000 align:start position:80%",
            "00:01.000 --> 00:02.000 align:center position:0%",
        ).forEach { assertEquals(it, normalizeYouTubeVtt(it)) }
    }

    @Test
    fun trackListUsesLocalFilesManualFirst() {
        val auto = YouTubeCaption("https://yt/a", "en", "English (auto-generated)*", autoGenerated = true)
        val manual = YouTubeCaption("https://yt/m", "de", "Deutsch", autoGenerated = false)
        val missing = YouTubeCaption("https://yt/x", "fr", "Français", autoGenerated = false)
        val tracks = youtubeCaptionTracks(listOf(auto, manual, missing, auto),
            mapOf("https://yt/a" to "file:///a.vtt", "https://yt/m" to "file:///m.vtt"))
        assertEquals(listOf("file:///m.vtt", "file:///a.vtt"), tracks.map { it.externalUrl })
        assertEquals(listOf("Deutsch", "English (auto-generated)"), tracks.map { it.title })
        assertTrue(tracks.all { it.type == MediaTrackType.SUBTITLE && !it.forced && !it.selected })
        assertEquals(listOf("de", "en"), tracks.map { it.languageCode })
    }

    @Test
    fun trackListIsBounded() {
        val many = (0 until 30).map { YouTubeCaption("https://yt/$it", "l$it", null, false) }
        assertEquals(16, youtubeCaptionsInLoadOrder(many).size)
        assertEquals("l0", youtubeCaptionTracks(many, many.associate { it.url to "file:///${it.languageCode}" }).first().title)
    }

    @Test
    fun existingSubtitleSettingsPickTheTrack() {
        val tracks = youtubeCaptionTracks(
            listOf(YouTubeCaption("https://yt/en", "en", "English", false), YouTubeCaption("https://yt/de", "de", "Deutsch", false)),
            mapOf("https://yt/en" to "file:///en.vtt", "https://yt/de" to "file:///de.vtt"))
        val full = SubtitlePreferences(mode = SubtitleMode.FULL, language = "de")
        assertEquals("file:///de.vtt", SubtitleSelectionPolicy.chooseMediaTrack(tracks, full, "en", "de-DE")?.externalUrl)
        assertEquals(null, SubtitleSelectionPolicy.chooseMediaTrack(tracks, SubtitlePreferences(mode = SubtitleMode.OFF), "en", "de-DE"))
    }
}
