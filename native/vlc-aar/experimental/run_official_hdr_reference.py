#!/usr/bin/env python3
"""Run the real GPU prepasses on independently supplied official reference
fixtures. Rights-cleared data stays local; missing data is a hard failure.

The supplier must attest that expected PQ RGB frames are official/reference
decoder outputs at the stated stage and frame, not generated by Ambient.
A checksum proves identity of supplied bytes, not the truth of that attestation.
"""
import argparse
import hashlib
import json
import pathlib
import subprocess
import sys

SOURCES = {
    "hdr10plus": ("https://dvb.org/specifications/verification-validation/hdr-test-content/",
                  "https://hdr10plus.org/"),
    "fel": ("https://ott.dolby.com/", "https://customer.dolby.com/")
}

def check_file(root, item):
    p = (root / item["path"]).resolve()
    if not p.is_relative_to(root) or not p.is_file():
        raise ValueError(f"missing or out-of-tree fixture: {p}")
    with p.open("rb") as f:
        actual = hashlib.file_digest(f, "sha256").hexdigest()
    if actual != item["sha256"].lower():
        raise ValueError(f"SHA256 mismatch: {p}")
    return str(p)

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("manifest", type=pathlib.Path)
    parser.add_argument("--gpu-runner", type=pathlib.Path, required=True)
    parser.add_argument("--report", type=pathlib.Path, required=True)
    args = parser.parse_args()
    if sys.byteorder != "little":
        raise ValueError("fixture schema requires little-endian host")
    root = args.manifest.resolve().parent
    data = json.loads(args.manifest.read_text())
    if data["schema"] != 1 or not data["cases"]:
        raise ValueError("empty or unknown official fixture manifest")
    modes = set()
    ids = set()
    results = []
    for case in data["cases"]:
        mode, cid = case["mode"], case["id"]
        if mode not in SOURCES or cid in ids or not cid:
            raise ValueError("unknown mode or duplicate case ID")
        ids.add(cid)
        if not case["source_url"].startswith(SOURCES[mode]):
            raise ValueError(f"{cid}: use the official provider/standards-body provenance URL")
        if not all(case.get(x) for x in ("provider_asset_id","reference_decoder_version","frame_id","usage_permission")):
            raise ValueError(f"{cid}: missing provenance, alignment or permissions")
        if case["reference_stage"] != "prepass-bt2020-pq-rgb":
            raise ValueError(f"{cid}: incompatible reference stage")
        if mode == "fel" and case.get("dolby_profile") != 7:
            raise ValueError("Profile 5/8 public kit cannot validate Profile 7 FEL")
        # Record original official source identity as well as extracted frame,
        # exact metadata and independent golden frame. Extraction/provenance
        # must be documented by the supplier, not inferred from filenames.
        check_file(root, case["source"])
        inp = check_file(root,case["input"])
        meta = check_file(root,case["metadata"])
        expected = check_file(root,case["expected"])
        limit = float(case["max_pq_error"])
        if not 0 < limit <= (0.0025 if mode == "hdr10plus" else 0.001):
            raise ValueError(f"{cid}: tolerance exceeds engineering guardrail")
        if mode == "hdr10plus":
            extra = [case["target_min_nits"],case["target_max_nits"],case["source_mastering_max_nits"]]
        else:
            extra = [case["el_width"],case["el_height"],check_file(root,case["el"])]
        command = [str(args.gpu_runner.resolve()),mode,str(case["width"]),str(case["height"]),
                   inp,meta,expected,str(limit),*map(str,extra)]
        p = subprocess.run(command, capture_output=True, text=True, timeout=180)
        print(p.stdout, end="")
        print(p.stderr, end="", file=sys.stderr)
        metrics = None
        for line in p.stdout.splitlines():
            if line.startswith("{"):
                metrics = json.loads(line)
        passed = p.returncode == 0 and metrics is not None
        results.append({"id":cid,"mode":mode,"source_url":case["source_url"],
                        "frame_id":case["frame_id"],"source_sha256":case["source"]["sha256"],
                        "reference_sha256":case["expected"]["sha256"],
                        "metrics":metrics,"passed":passed,"returncode":p.returncode})
        if passed:
            modes.add(mode)
    passed = modes == {"hdr10plus","fel"} and all(x["passed"] for x in results)
    args.report.write_text(json.dumps({"passed":passed,"cases":results},indent=2)+"\n")
    return 0 if passed else 1

if __name__ == "__main__":
    sys.exit(main())
